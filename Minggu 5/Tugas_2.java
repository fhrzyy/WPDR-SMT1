public class Tugas_2 {
    public static void main(String[] args) {
        int bulan, year;
        
        bulan = 1;
        year = 2002;
        switch (bulan) {
            case 1: 
                switch (year) {
                    case 2002:
                        System.out.println("Bulan 1 tahun 2002");
                        break;
                        case 2003:
                        System.out.println();
                }
            case 2:
                default:
                System.out.println("");
                break;
        }

    }
}
