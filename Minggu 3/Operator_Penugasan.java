public class Operator_Penugasan {
    public static void main(String[] args) {
        int a = 4;
        int b;

        System.out.println("a = 4");
        
        b = a;
        System.out.println("b = a : " +b);

        b += a;
        System.out.println("b += a : " + b);
        
        b *= a;
        System.out.println("b *= a : " + b);

    }
}
