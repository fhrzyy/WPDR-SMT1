public class Operator_Relasional {
    public static void main(String[] args) {

        int a = 7, b = 11;

        System.out.println("a adalah " + a + "dan b adalah " + b);

        System.out.println("a == b :");
        System.out.println(a == b);

        System.out.println("a != b : ");
        System.out.println(a != b);

        System.out.println("a > b : ");
        System.out.println(a > b);

        System.out.println("a < b : ");
        System.out.println(a < b);

        System.out.println("a >= b : ");
        System.out.println(a >= b);

        System.out.println("a <= b : ");
        System.out.println(a <= b);

    }
}
